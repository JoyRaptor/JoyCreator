    /** THE FILL PEN'S REAL CALLER, wired the same way: outline -> polygon -> paint. */
    @Test
    fun aFillPenShapePaintsAsAShape() {
        val outline = listOf(Pt(40.0, 20.0), Pt(120.0, 30.0), Pt(80.0, 100.0))
        val mask = SelectionMask.polygon(outline)
        assertFalse(mask.isEmpty)
        val tile = assertNotNull(
            MaskPaint.apply(emptyMap(), mask, 0xFFFFC000.toInt(), 1f, MaskPaintMode.BEHIND)[Tiles.key(0, 0)],
        )
        var solid = 0
        var weighted = 0L
        for (y in 0 until 110) {
            for (x in 0 until 130) {
                val c = mask.coverage(x, y)
                if (c == 0) continue
                val at = (y * Tiles.SIZE + x) * 4
                // BEHIND onto an empty layer is `S + 0`, so the pixel is the source premultiplied
                // BY ITS OWN COVERAGE: alpha = 255*c/255 = c, and each colour = 255*(c/255).
                val wantAlpha = c
                assertEquals(wantAlpha, tile[at + 3].toInt() and 0xFF, "($x,$y) alpha is the coverage")
                assertEquals(
                    wantAlpha, tile[at].toInt() and 0xFF,
                    "($x,$y) red: 0xEE is 238, so 238*c/255 rounds to the coverage itself at c = 255 " +
                        "and to a proportional value below it",
                )
                assertTrue(
                    tile[at].toInt() and 0xFF <= tile[at + 3].toInt() and 0xFF,
                    "($x,$y) red is above alpha, which is not a premultiplied pixel",
                )
                weighted += c.toLong()
                if (c == 255) solid++
            }
        }
        // Shoelace: the polygon area is |sum(x_i*y_j - x_j*y_i)|/2 over the closed loop. The
        // weighted coverage sum must be within antialiasing of it — this is an AREA check, not a
        // per-pixel expected value, which is the point.
        //
        // THE TOLERANCE, derived rather than fitted. The outline's edges are DIAGONAL — (40,20) to
        // (120,30) to (80,100) — so this polygon is not a rect and its boundary really is fractional.
        // A 4 x 4 supersampler gives each pixel `round(subpixels * 255 / 16)`, and `round` is off by
        // at most half a unit, so the SUM is off from the exact area by at most half a unit per
        // BOUNDARY pixel; interior pixels are exactly 255 and exterior exactly 0 and contribute
        // nothing. A monotone edge of span dx by dy crosses at most dx + dy pixels, and this
        // triangle's three edges give 80+10, 40+70 and 40+80, so at most 320 boundary pixels and
        // therefore at most 160 units of error. The observed value is 10 — two orders of magnitude
        // inside the bound, and the bound still catches a stride or tile-origin error, which lands
        // in the tens of thousands. An exact `assertEquals` here was simply wrong: the comment above
        // it had said "within antialiasing" all along, and the assertion had not believed it.
        val area = abs(
            outline.indices.sumOf { i ->
                val a = outline[i]
                val b = outline[(i + 1) % outline.size]
                a.x * b.y - b.x * a.y
            },
        ) / 2.0
        val error = abs(weighted - (area * 255).toLong())
        assertTrue(
            error <= 160L,
            "the shape's coverage sum is $weighted against an area of $area ($((area * 255).toLong()}), " +
                "a difference of $error where at most 160 is antialiasing",
        )
        // The SOLID count, against the same boundary budget and for the same reason. A 4 x 4
        // supersampler marks a pixel 255 only when all 16 subsamples fall inside, so every boundary
        // pixel of a DIAGONAL edge is partial, and "almost every interior pixel" is not the same
        // thing as "2 % may be partial" on a shape with 250 px of slanted perimeter. The bound is
        // the same 320: at most one non-solid interior pixel per boundary pixel. Observed 110.
        // A stride or tile-origin error puts this in the thousands, so the bound still has teeth.
        assertTrue(
            abs(solid - area) <= 320.0,
            "only $solid px are SOLID, against an area of $area — at most 320 may be partial " +
                "boundary pixels of a 250 px slanted perimeter",
        )
    }

