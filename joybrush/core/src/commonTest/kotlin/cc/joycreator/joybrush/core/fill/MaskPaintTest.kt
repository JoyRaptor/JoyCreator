    /**
     * The rounding, named directly.
     *
     * `floor(v + 0.5)` — the form the rest of the engine uses (`Resample.toByte255`,
     * `SelectionMask.subtract`) — returns 1 for `0.49999999999999994`, because that plus 0.5 is
     * exactly 1.0 in IEEE 754. The truncating form [MaskPaint.round255] uses is exact for every
     * double, and this is the case that proves it.
     */
    @Test
    fun theRoundingIsExactAtTheHalfAndNotOneUlpPastIt() {
        assertEquals(1, MaskPaint.round255(0.5), "0.5 rounds UP (half up, as documented)")
        assertEquals(0, MaskPaint.round255(0.49999999999999994), "one ULP below 0.5 rounds DOWN")
        assertEquals(0, MaskPaint.round255(0.4999999999999999), "and so do two ULPs below")
        assertEquals(255, MaskPaint.round255(254.5))
        assertEquals(254, MaskPaint.round255(254.49999999999997), "one ULP below 254.5 rounds DOWN")
        assertEquals(0, MaskPaint.round255(0.0))
        assertEquals(0, MaskPaint.round255(-3.0), "clamped, not wrapped: a negative becomes 0")
        assertEquals(255, MaskPaint.round255(1e9), "clamped, not wrapped: a huge value becomes 255")
        for (k in 0..255) {
            val base = k.toDouble()
            assertEquals(k, MaskPaint.round255(base), "$base")
            // `nextDown`, NOT `base + 0.49999999999999994`. That literal is a trap, and it made this
            // test assert two contradictory things at once: for every integer `base` in this range,
            // `base + 0.49999999999999994` rounds back UP to exactly `base + 0.5` in the addition
            // (the true sum sits within half an ULP of it), so the expression is `base + 0.5` and
            // the correct answer is `k + 1` — which is what the very next line asserts. The literal
            // is only a value strictly below `0.5` when `base` is 0, which is line 2 above.
            // `nextDown(base + 0.5)` says "just under the half" and MEANS it, for every `k`.
            val justUnder = (base + 0.5).nextDown()
            assertTrue(justUnder < base + 0.5, "nextDown must really be under the half at $base")
            assertEquals(k, MaskPaint.round255(justUnder), "$base + just under .5")
            // And the same value through the form this function exists to avoid. It is wrong at
            // k = 0 and RIGHT everywhere else, which is the honest shape of the problem and worth
            // pinning exactly rather than rounding off in a comment: at k = 0 the sum is
            // 0.9999999999999999444, within half an ULP of 1.0, so the addition rounds it up to
            // exactly 1.0 and `floor` returns 1 for a value that must round DOWN to 0. From k = 1
            // upward the sum is representable and `floor` happens to land right. A function that is
            // wrong once in 256 is wrong, because the once is a pixel.
            if (k == 0) {
                assertEquals(1, floor(justUnder + 0.5).toInt(), "floor(v+0.5) is the wrong one — here")
            } else {
                assertEquals(k, floor(justUnder + 0.5).toInt(), "floor(v+0.5) happens to agree at $k")
            }
            // The top of the range is where the CLAMP is, not the rounding: 255.5 and anything just
            // over it round to 256, which is not a byte, and the documented answer is 255. So k = 255
            // expects k and not k + 1 — asserted explicitly rather than left to fall out of a
            // `coerceAtMost` nobody thought about when the sweep was written.
            val top = k == 255
            assertEquals(if (top) k else k + 1, MaskPaint.round255(base + 0.5), "$base + .5")
            assertEquals(
                if (top) k else k + 1, MaskPaint.round255((base + 0.5).nextUp()),
                "$base + just over .5" + if (top) " (clamped, not wrapped)" else "",
            )
        }
    }

