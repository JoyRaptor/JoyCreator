/**
 * JB-2.07a — painting a [SelectionMask] through a layer's premultiplied tiles. The raster maths
 * of the fill pen (LEAD_RULINGS R21: the fill pen is a brush, not a tool; this is what draws it)
 * and of the tap fill, which differs only in where the mask came from.
 *
 * ## WHERE THE EXPECTED VALUES COME FROM, which is the point of this file
 *
 * Four sources, and they are not interchangeable:
 *
 *  1. [theGoldenTableAgreesWithAnIndependentExactRationalModel] — 3123 rows generated by a second
 *     implementation in exact rational arithmetic (`fractions.Fraction`, never binary floating
 *     point) that never saw this module's source. This is the one that CAN disagree with a bug,
 *     because a bug and a hand-derived number come from the same head. Everything else here is a
 *     check on the table's own claims.
 *  2. [theWholeLassoAgreesWithTheOnePixelFunctionPixelForPixel] — the invariant that keeps
 *     [MaskPaint.apply] (the tile walk) and [MaskPaint.pixel] (the arithmetic) from drifting
 *     apart. The golden table only sees `pixel`, so without this a change to `apply` alone would
 *     be invisible to it.
 *  3. Invariants computed a DIFFERENT WAY — the painted area against the mask's own coverage sum,
 *     a shape against its half turn, the second pass of a solid fill. Each has an answer that
 *     does not require knowing the formula.
 *  4. Hand-derived values, and there are only a handful, each with its derivation in a comment
 *     beside it — Lead ruling R9's standing rule: an expected value may be changed only with its
 *     derivation written down, never to make a run go green.
 */
class MaskPaintTest {

    // ── the golden table ──────────────────────────────────────────────────────────

    @Test
    fun theGoldenTableAgreesWithAnIndependentExactRationalModel() {
        assertEquals(
            MaskPaintGolden.EXPECTED_SIZE, MaskPaintGolden.ROWS.size,
            "the table is the evidence, and its three parts must all still be joined in",
        )
        assertTrue(MaskPaintGolden.ROWS.size > 3000, "the table is the evidence; do not shrink it")
        val out = IntArray(4)
        var checked = 0
        for (row in MaskPaintGolden.ROWS) {
            pixel(row.mode, row.argb, row.opacity, row.coverage, row.dest, out)
            for (c in 0..3) {
                assertEquals(
                    row.expect[c],
                    out[c],
                    "channel $c of ${row.mode} argb=0x${row.argb.toUInt().toString(16)} " +
                        "opacity=${row.opacity} coverage=${row.coverage} " +
                        "dest=${row.dest.joinToString(",")} — the exact-rational model says " +
                        "${row.expect.joinToString(",")}, MaskPaint said ${out.joinToString(",")}",
                )
            }
            checked++
        }
        assertEquals(MaskPaintGolden.ROWS.size, checked)
    }

    /**
     * The table covers all three modes and both ends of the opacity and coverage ranges. If a
     * future edit narrows any of them the table quietly stops being evidence, so the coverage is
     * asserted rather than assumed.
     */
    @Test
    fun theTableCoversEveryModeAndTheEndsOfEveryRange() {
        assertEquals(
            MaskPaintMode.entries.toSet(),
            MaskPaintGolden.ROWS.map { it.mode }.toSet(),
            "a mode with no rows is an untested mode",
        )
        val coverages = MaskPaintGolden.ROWS.map { it.coverage }.toSet()
        assertEquals(0, coverages.min(), "coverage 0 — the mask misses the pixel")
        assertEquals(255, coverages.max(), "coverage 255 — solid")
        // Not an exact count: the table's row count is the generator's business, and asserting a
        // number here would mean editing this test every time a row is added. What has to hold is
        // that solid coverage is exercised across every colour and every mode, which is
        // `>= 3 modes * a spread of colours`.
        assertTrue(
            MaskPaintGolden.ROWS.count { it.coverage == 255 } > 200,
            "solid coverage must be exercised across every mode and a spread of colours",
        )
        assertTrue(
            MaskPaintGolden.ROWS.any { it.opacity == 0f }, "opacity 0")
        assertTrue(
            MaskPaintGolden.ROWS.any { it.opacity == 1f }, "opacity 1")
        assertTrue(
            MaskPaintGolden.ROWS.any { row -> row.dest.all { c -> c == 0 } },
            "the empty destination — a fill onto blank paper is the common case",
        )
        assertTrue(
            MaskPaintGolden.ROWS.any { row -> row.dest[3] == 255 && row.dest[0] == 255 },
            "the opaque destination — BEHIND over it is a no-op and the table says what that is",
        )
        // The clamp's only reason to exist. Without a non-premultiplied destination in the table
        // the colour <= alpha clamp could be deleted and the table would stay green.
        assertTrue(
            MaskPaintGolden.ROWS.any { row -> row.dest[0] > row.dest[3] },
            "a destination with colour > alpha, which is what the premultiplied clamp is for",
        )
        assertTrue(
            MaskPaintGolden.ROWS.all { row -> row.expect[0] <= row.expect[3] },
            "every expected pixel is premultiplied, including the ones that started un-premultiplied",
        )
    }

    // ── apply is pixel, everywhere ────────────────────────────────────────────────

    /**
     * THE BRIDGE TEST, and the reason [MaskPaint.pixel] is a public door at all.
     *
     * The golden table tests the arithmetic; it cannot see the tile walk. So walk REAL masks —
     * a lasso with antialiased edges, a shape with a hole, shapes across both tile seams, a
     * shape at negative coordinates — and check every pixel of every returned tile against the
     * one-pixel function. Every way the walk can be wrong (a coverage read from the wrong tile, a
     * row stride of 256 instead of 256*4, a premultiplied/straight mix-up) moves a pixel, and this
     * moves all of them.
     *
     * The destination VARIES with position, so a walk that reads the wrong pixel's backdrop still
     * fails here; a constant backdrop would let a whole class of indexing bug through.
     */
    @Test
    fun theWholeLassoAgreesWithTheOnePixelFunctionPixelForPixel() {
        for (mask in shapes()) {
            assertFalse(mask.isEmpty, "a test shape that rasterised to nothing tests nothing")
            for (mode in MaskPaintMode.entries) {
                for (argb in listOf(0xFFFF0000.toInt(), 0xFF3399CC.toInt(), 0xFF000000.toInt())) {
                    for (opacity in listOf(1f, 0.5f, 0.25f)) {
                        val layer = rampLayer(mask)
                        val changed = MaskPaint.apply(layer, mask, argb, opacity, mode)
                        for (key in changed.keys) {
                            val tile = changed[key] ?: continue
                            val cov = assertNotNull(mask.tile(key), "changed tile $key has no mask")
                            val tx = Tiles.tx(key) * Tiles.SIZE
                            val ty = Tiles.ty(key) * Tiles.SIZE
                            for (row in 0 until Tiles.SIZE) {
                                for (col in 0 until Tiles.SIZE) {
                                    val at = (row * Tiles.SIZE + col) * 4
                                    val c = cov[row * Tiles.SIZE + col].toInt() and 0xFF
                                    val x = tx + col
                                    val y = ty + row
                                    val d = rampPixel(x, y)
                                    if (c == 0) {
                                        assertContentEquals(
                                            ByteArray(4) { d[it].toByte() },
                                            tile.copyOfRange(at, at + 4),
                                            "mode $mode: ($x,$y) is not covered, so the destination " +
                                                "must be carried through the tile byte for byte",
                                        )
                                        continue
                                    }
                                    val out = pixel(mode, argb, opacity, c, d, IntArray(4))
                                    for (ch in 0..3) {
                                        assertEquals(
                                            out[ch],
                                            tile[at + ch].toInt() and 0xFF,
                                            "mode $mode argb=0x${argb.toUInt().toString(16)} " +
                                                "opacity=$opacity pixel ($x,$y) coverage=$c channel $ch",
                                        )
                                    }
                                    pixelsWalked++
                                }
                            }
                        }
                    }
                }
            }
        }
        assertTrue(
            pixelsWalked > 200_000,
            "only $pixelsWalked covered pixels walked; too few for this to be evidence",
        )
    }

    private var pixelsWalked = 0

    // ── invariants computed a different way ───────────────────────────────────────

    /**
     * AREA, NOT FORMULA. A solid fill onto an empty layer paints an alpha equal to the coverage
     * at every pixel, so the SUM of the alpha of a filled shape must equal the SUM of the mask's
     * coverage over the same box — a number computed by a completely different route (a summation
     * over `SelectionMask.coverage`) and never through the blend arithmetic.
     *
     * This is the check that catches a stride or an off-by-one in the tile walk, because those
     * move the total far more visibly than they move any one pixel.
     */
    @Test
    fun thePaintedAreaEqualsTheSelectedArea() {
        val box = RectPx(20, 30, 200, 140)
        val mask = SelectionMask.rect(box)
        val selected = coverageSum(mask, box)
        assertEquals(200L * 140L * 255L, selected, "SelectionMask.rect is exactly 255 inside, so this is exact")
        for (opacity in listOf(1f, 0.5f, 0.25f, 0.125f)) {
            val painted = totalAlpha(
                MaskPaint.apply(emptyMap(), mask, 0xFF204080.toInt(), opacity, MaskPaintMode.FILL),
            )
            val expected = selected.toDouble() * opacity
            if (opacity == 1f) {
                assertEquals(selected, painted, "at full opacity the painted alpha IS the coverage")
            } else {
                // Each pixel's alpha is round(255 * (c/255) * o) = round(c*o), so the total is
                // within half a unit per painted pixel of `selected * o`. The bound is 200*140/2
                // pixels, which is loose but not so loose that a stride error survives it.
                assertTrue(
                    abs(painted - expected) <= (box.w.toLong() * box.h.toLong()),
                    "opacity $opacity: painted alpha total $painted, expected about ${expected.toInt()}",
                )
            }
        }
    }

    /**
     * SYMMETRY. A square and the same square reflected through the origin must paint the same
     * total alpha, and — because the arithmetic is per pixel and knows nothing about shapes — the
     * same answer at the pixel that maps onto the pixel that maps.
     *
     * The reflection is exact for a square, so no area correction is needed; the destination
     * ramp is a function of position, so this is a real check rather than two equal constants.
     */
    @Test
    fun aShapeAndItsMirrorPaintTheSameAmount() {
        val a = SelectionMask.polygon(
            listOf(Pt(20.0, 30.0), Pt(180.0, 30.0), Pt(180.0, 140.0), Pt(20.0, 140.0)),
        )
        val b = SelectionMask.polygon(
            listOf(Pt(-180.0, -140.0), Pt(-20.0, -140.0), Pt(-20.0, -30.0), Pt(-180.0, -30.0)),
        )
        // The premise, pinned first: this reflection is exact for a square, so a and b really do
        // have the same coverage multiset. Without it, an equality below would be vacuous.
        assertEquals(
            coverageSum(a, RectPx(20, 30, 160, 110)),
            coverageSum(b, RectPx(-180, -140, 160, 110)),
            "the two squares must be reflections of each other, or the equality below means nothing",
        )
        for (mode in MaskPaintMode.entries) {
            for (opacity in listOf(1f, 0.6f)) {
                val layer = rampLayer(a) + rampLayer(b)
                val ca = MaskPaint.apply(layer, a, 0xFF00FF00.toInt(), opacity, mode)
                val cb = MaskPaint.apply(layer, b, 0xFF00FF00.toInt(), opacity, mode)
                assertEquals(
                    totalAlpha(ca), totalAlpha(cb),
                    "mode $mode opacity $opacity: reflecting a shape changed the painted total, and " +
                        "the per-pixel arithmetic cannot know a shape from its reflection",
                )
                assertFalse(ca.isEmpty(), "the square painted nothing at all")
            }
        }
    }

    /**
     * A SECOND PASS OF A FULLY OPAQUE FILL IS A COMPLETE NO-OP — reported as an EMPTY change set,
     * not as equal bytes.
     *
     * This is the same property twice, and both halves matter. Source-over with `a = 1` REPLACES,
     * and destination-over with `room = 0` adds nothing, so the second pass produces bytes
     * identical to the first's. And Decision 2 says identical bytes are NOT reported — so the
     * second pass records no undo step. A fill that accumulated instead would read as a fill that
     * goes darker every time a person undoes and redoes it, which is the classic sign of a blend
     * compositing onto itself rather than replacing.
     */
    @Test
    fun aSecondPassOfAnOpaqueFillReportsNothingAtAll() {
        // 300 x 300 from the origin crosses BOTH seams, so four tiles: a walk that counted two
        // would already be wrong about which tiles a shape touches.
        val mask = SelectionMask.rect(RectPx(0, 0, 300, 300))
        for (mode in listOf(MaskPaintMode.FILL, MaskPaintMode.BEHIND)) {
            val once = MaskPaint.apply(emptyMap(), mask, 0xFFEE8800.toInt(), 1f, mode)
            assertEquals(4, once.size, "mode $mode: a 300 x 300 square at the origin is four tiles")
            val twice = MaskPaint.apply(once.asLayer(), mask, 0xFFEE8800.toInt(), 1f, mode)
            assertTrue(
                twice.isEmpty(),
                "mode $mode: an opaque fill over its own result changes nothing, so nothing is " +
                    "reported. Got keys ${twice.keys}",
            )
        }
    }

    /**
     * ERASE TWICE IS ONCE, and it is measured rather than asserted. `D*(1-a)` at `a = 1` empties
     * the tile on the first pass and the second pass finds nothing there, so it reports nothing:
     * an erase over already-empty paper costs no undo step.
     */
    @Test
    fun aSecondEraseOverEmptyPaperRecordsNothing() {
        val mask = SelectionMask.rect(RectPx(0, 0, 64, 64))
        val painted = MaskPaint.apply(emptyMap(), mask, 0xFFFFFFFF.toInt(), 1f, MaskPaintMode.FILL)
        val erased = MaskPaint.apply(painted.asLayer(), mask, 0, 1f, MaskPaintMode.ERASE)
        assertEquals(
            listOf(Tiles.key(0, 0)), erased.keys.toList(),
            "erasing a solid fill from a solid fill empties exactly the tile it painted",
        )
        assertNull(erased[Tiles.key(0, 0)], "an emptied tile is a DELETE (null), not a zero tile")
        // The same call again, from the same starting layer, is the same change set.
        assertContentEquals(
            erased.keys.toList(),
            MaskPaint.apply(painted.asLayer(), mask, 0, 1f, MaskPaintMode.ERASE).keys.toList(),
        )
    }

    /**
     * THE OPPOSITE, and it is why Decision 2 is not "drop empty tiles and be done". A
     * [MaskPaintMode.BEHIND] under fully opaque paint changes nothing and so is not in the answer
     * at all. Dropping the tile instead would DELETE a tile full of somebody's drawing, which is
     * the worst thing this function could do.
     */
    @Test
    fun behindFullyOpaquePaintReportsNothingRatherThanDeletingIt() {
        val mask = SelectionMask.rect(RectPx(0, 0, 64, 64))
        val original = solidTile(9, 0, 0, 255)
        val layer = mapOf(Tiles.key(0, 0) to original)
        val changed = MaskPaint.apply(layer, mask, 0xFFFF0000.toInt(), 1f, MaskPaintMode.BEHIND)
        assertTrue(changed.isEmpty(), "a BEHIND under opaque paint is a no-op, so it is not reported")
        assertContentEquals(
            original, layer.getValue(Tiles.key(0, 0)),
            "the caller's tile was written to, which would also break the undo snapshot",
        )
    }

    // ── the spec's seven tests ────────────────────────────────────────────────────

    /** Spec test 1: FILL a 10 x 10 square in opaque red on an empty layer -> 100 red pixels. */
    @Test
    fun fillASquareMaskInOpaqueRedOnAnEmptyLayer() {
        val mask = SelectionMask.rect(RectPx(5, 5, 10, 10))
        val changed = MaskPaint.apply(emptyMap(), mask, 0xFFFF0000.toInt(), 1f, MaskPaintMode.FILL)
        assertEquals(1, changed.size, "one 10 x 10 square is one tile")
        val tile = assertNotNull(changed[Tiles.key(0, 0)])
        var red = 0
        for (y in 0 until Tiles.SIZE) {
            for (x in 0 until Tiles.SIZE) {
                val at = (y * Tiles.SIZE + x) * 4
                if (mask.coverage(x, y) == 0) {
                    assertEquals(0, tile[at + 3].toInt() and 0xFF, "($x,$y) is outside the mask")
                    continue
                }
                assertEquals(255, tile[at].toInt() and 0xFF, "($x,$y) red")
                assertEquals(0, tile[at + 1].toInt() and 0xFF, "($x,$y) green")
                assertEquals(0, tile[at + 2].toInt() and 0xFF, "($x,$y) blue")
                assertEquals(255, tile[at + 3].toInt() and 0xFF, "($x,$y) alpha")
                red++
            }
        }
        assertEquals(100, red, "10 x 10 is 100 px, and SelectionMask.rect is exactly 255 inside")
    }

    /**
     * Spec test 2: FILL at opacity 0.5 over opaque blue -> (128, 0, 128, 255).
     *
     * DERIVATION. Opaque blue is premultiplied (0, 0, 255, 255). Red at `a = 0.5` gives the
     * premultiplied source (127.5, 0, 0, 127.5), and FILL is `S + D*(1-a)` = (127.5, 0, 127.5,
     * 127.5 + 127.5) = (127.5, 0, 127.5, 255). Rounded half up: (128, 0, 128, 255). The alpha is
     * exactly 255 because an opaque backdrop under source-over stays opaque.
     */
    @Test
    fun fillAtHalfOpacityOverOpaqueBlue() {
        val mask = SelectionMask.rect(RectPx(0, 0, 8, 8))
        val layer = mapOf(Tiles.key(0, 0) to solidTile(0, 0, 255, 255))
        val tile = assertNotNull(
            MaskPaint.apply(layer, mask, 0xFFFF0000.toInt(), 0.5f, MaskPaintMode.FILL)[Tiles.key(0, 0)],
        )
        for (y in 0 until 8) {
            for (x in 0 until 8) {
                val at = (y * Tiles.SIZE + x) * 4
                val got = (0..3).map { tile[at + it].toInt() and 0xFF }
                assertTrue(
                    abs(got[0] - 128) <= 1 && got[1] == 0 && abs(got[2] - 128) <= 1,
                    "($x,$y) expected about (128, 0, 128, 255) +/-1, got ${got.joinToString(",")}",
                )
                assertEquals(255, got[3], "($x,$y) alpha stays opaque: 127.5 + 127.5 is 255")
            }
        }
    }

    /**
     * Spec test 3: ERASE the same square out of an opaque layer -> those pixels 0; ERASE a whole
     * tile's area -> that tile is returned as null.
     */
    @Test
    fun eraseASquareOutOfAnOpaqueLayer() {
        val mask = SelectionMask.rect(RectPx(0, 0, 10, 10))
        val layer = mapOf(Tiles.key(0, 0) to solidTile(0, 0, 255, 255))
        val tile = assertNotNull(
            MaskPaint.apply(layer, mask, 0, 1f, MaskPaintMode.ERASE)[Tiles.key(0, 0)],
            "a partial erase is an edit, not a delete",
        )
        for (y in 0 until 64) {
            for (x in 0 until 64) {
                val at = (y * Tiles.SIZE + x) * 4
                val inside = x < 10 && y < 10
                // Outside the square the tile is the opaque blue it started as, byte for byte.
                val want = if (inside) listOf(0, 0, 0, 0) else listOf(0, 0, 255, 255)
                for (c in 0..3) {
                    assertEquals(
                        want[c], tile[at + c].toInt() and 0xFF,
                        "($x,$y) channel $c (inside=$inside)",
                    )
                }
            }
        }
        val whole = MaskPaint.apply(
            layer, SelectionMask.rect(RectPx(0, 0, 256, 256)), 0, 1f, MaskPaintMode.ERASE,
        )
        assertEquals(listOf(Tiles.key(0, 0)), whole.keys.toList())
        assertNull(whole[Tiles.key(0, 0)], "a tile erased entirely comes back as null (delete it)")
    }

    /**
     * Spec test 4: BEHIND over a layer with a black 1-px line through the square — the line is
     * untouched, the rest is red, and a soft line-edge pixel gets red only in its transparent
     * share.
     *
     * DERIVATION. The line pixel is opaque black (0, 0, 0, 255), so `room = 1 - 255/255 = 0` and
     * BEHIND adds `S*0`: the line is untouched. Every other pixel in the square is transparent
     * (`room = 1`) and becomes the source exactly — (255, 0, 0, 255) for red.
     *
     * THE SOFT EDGE, which is not a special case. A half-covered line pixel (0, 0, 0, 128) has
     * `room = 1 - 128/255 = 127/255`, so the red landing there is `255 * 127/255 = 127`
     * premultiplied and the new alpha is `128 + 255*127/255 = 255`. That is "red only in the
     * transparent share": 127/255 of the pixel's capacity was free, and all of it is now red.
     */
    @Test
    fun behindLeavesTheLineAloneAndColoursTheRest() {
        val mask = SelectionMask.rect(RectPx(0, 0, 16, 16))
        val layer = ByteArray(Tiles.SIZE * Tiles.SIZE * 4)
        for (x in 0 until 16) {
            var at = (8 * Tiles.SIZE + x) * 4
            layer[at + 3] = 255.toByte()
            at = (9 * Tiles.SIZE + x) * 4
            layer[at + 3] = 128.toByte()
        }
        val tile = assertNotNull(
            MaskPaint.apply(
                mapOf(Tiles.key(0, 0) to layer), mask, 0xFFFF0000.toInt(), 1f, MaskPaintMode.BEHIND,
            )[Tiles.key(0, 0)],
        )
        for (x in 0 until 16) {
            for (c in 0..3) {
                val solid = (8 * Tiles.SIZE + x) * 4 + c
                assertEquals(layer[solid].toInt() and 0xFF, tile[solid].toInt() and 0xFF, "line ($x,8) channel $c")
            }
            val soft = (9 * Tiles.SIZE + x) * 4
            assertEquals(127, tile[soft].toInt() and 0xFF, "soft edge red: 255 * 127/255")
            assertEquals(0, tile[soft + 1].toInt() and 0xFF, "soft edge green")
            assertEquals(0, tile[soft + 2].toInt() and 0xFF, "soft edge blue")
            assertEquals(255, tile[soft + 3].toInt() and 0xFF, "soft edge alpha: 128 + 127")
        }
        for (y in 0 until 8) {
            for (x in 0 until 16) {
                val at = (y * Tiles.SIZE + x) * 4
                assertEquals(255, tile[at].toInt() and 0xFF, "($x,$y) red")
                assertEquals(255, tile[at + 3].toInt() and 0xFF, "($x,$y) alpha")
            }
        }
    }

    /**
     * Spec test 5: nothing changes -> an empty result. The first three are the spec's own cases;
     * the fourth is the one worth adding, because a NaN opacity is 1 and an opaque fill over
     * opaque paper is therefore NOT empty — a check that would have passed for the wrong reason
     * if the NaN had silently become 0.
     */
    @Test
    fun nothingChangingReturnsNothing() {
        val mask = SelectionMask.rect(RectPx(0, 0, 32, 32))
        val opaque = mapOf(Tiles.key(0, 0) to solidTile(0, 0, 0, 255))
        assertTrue(
            MaskPaint.apply(emptyMap(), mask, 0xFFFF0000.toInt(), 1f, MaskPaintMode.ERASE).isEmpty(),
            "ERASE on empty canvas: the tile is already all zero, so nothing changes",
        )
        assertTrue(
            MaskPaint.apply(opaque, mask, 0xFFFF0000.toInt(), 1f, MaskPaintMode.BEHIND).isEmpty(),
            "BEHIND under fully opaque paint",
        )
        assertTrue(
            MaskPaint.apply(opaque, mask, 0xFFFF0000.toInt(), 0f, MaskPaintMode.FILL).isEmpty(),
            "an opacity of 0 is a no-op in every mode",
        )
        assertFalse(
            MaskPaint.apply(opaque, mask, 0xFFFF0000.toInt(), Float.NaN, MaskPaintMode.FILL).isEmpty(),
            "a NaN opacity is 1, and white over black changes black — so this is NOT empty. If it " +
                "were, the NaN would have become 0 and this test would be passing for the wrong reason",
        )
    }

    /**
     * Spec test 6: a lasso crossing a tile seam at x = 256 paints both tiles with no seam artefact.
     *
     * The check is a COLOUR CONTINUITY check, not a "both keys are present" check: the two pixels
     * either side of the seam are one pixel apart in the document, so their alpha must be equal.
     * A walk that mis-strided by one byte, or read the wrong tile's coverage, shows here and
     * nowhere else in the suite.
     */
    @Test
    fun aLassoOverATileSeamPaintsBothTilesWithNoSeam() {
        val mask = SelectionMask.rect(RectPx(250, 20, 12, 40))
        val changed = MaskPaint.apply(emptyMap(), mask, 0xFF40C0FF.toInt(), 1f, MaskPaintMode.FILL)
        assertEquals(2, changed.size, "x = 250..261 crosses 256, so two tiles are in play")
        val left = assertNotNull(changed[Tiles.key(0, 0)])
        val right = assertNotNull(changed[Tiles.key(1, 0)])
        for (y in 20 until 60) {
            val l = (y * Tiles.SIZE + 255) * 4 + 3
            val r = (y * Tiles.SIZE) * 4 + 3
            assertEquals(255, left[l].toInt() and 0xFF, "row $y, x = 255")
            assertEquals(255, right[r].toInt() and 0xFF, "row $y, x = 256")
        }
        // And the shape is pixel-exact either side of the seam: a rect has no antialiasing, so
        // x = 249 and x = 262 are untouched in their own tiles and x = 255 and x = 256 are solid.
        assertEquals(0, left[(20 * Tiles.SIZE + 249) * 4 + 3].toInt() and 0xFF, "x = 249 is outside")
        assertEquals(255, left[(20 * Tiles.SIZE + 255) * 4 + 3].toInt() and 0xFF, "x = 255 is inside")
        assertEquals(255, right[(20 * Tiles.SIZE) * 4 + 3].toInt() and 0xFF, "x = 256 is inside")
