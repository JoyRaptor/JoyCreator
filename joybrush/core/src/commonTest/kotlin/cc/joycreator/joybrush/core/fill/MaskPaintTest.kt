    /** A full tile of one premultiplied colour. */
    private fun solidTile(r: Int, g: Int, b: Int, a: Int): ByteArray {
        val t = ByteArray(Tiles.SIZE * Tiles.SIZE * 4)
        for (i in t.indices step 4) {
            t[i] = r.toByte(); t[i + 1] = g.toByte(); t[i + 2] = b.toByte(); t[i + 3] = a.toByte()
        }
        return t
    }

    /**
     * A premultiplied destination that VARIES with position, so an indexing bug in the tile walk
     * cannot pass by reading the same constant backdrop every time. The colours are written under
     * the alpha, so this is a legal premultiplied pixel at every point — the illegal ones are in
     * [everyPixelThatComesOutIsPremultiplied].
     *
     * THROUGH THE PIXEL'S CENTRE, and that is not a style choice. `x` and `y` here are the LOWER-LEFT
     * DOCUMENT INDEX of a pixel, and the mirror of pixel index `i` under `(x, y) -> (-x, -y)` is
     * `-i - 1`, not `-i`: pixel `i` covers `[i, i+1)` and its mirror covers `[-i-1, -i)`. So `abs(i)`
     * is NOT the mirror of `abs(-i-1)` — for `i = 20` the two are 20 and 21 — and a ramp built on
     * `abs(i)` is not symmetric under the reflection the test is about. `abs(2*i + 1)` is: it is
     * `|centre|` in doubled units, and `|2*(-i-1) + 1| = |2*i + 1|`.
     *
     * This was a real red test, not a hypothetical: the whole-tile alpha totals differed by 19 808
     * with the index-based ramp, and the difference was entirely in the part of the tile the fill
     * never touched, because tile `(0, 0)` spans indices `0..255` (so `px` runs 0..255) while tile
     * `(-1, -1)` spans `-256..-1` (so `px` runs 1..256). The paint was symmetric the whole time.
     */
    private fun rampPixel(x: Int, y: Int): IntArray {
        val px = abs(2 * x + 1)
        val py = abs(2 * y + 1)
        val a = (px * 2 + py) % 200 + 55
        return intArrayOf(
            ((px + py) % 200).coerceAtMost(a),
            ((px + py) / 2 % 200).coerceAtMost(a),
            ((px * 3 + py) % 200).coerceAtMost(a),
            a,
        )
    }

    /** A layer of [rampPixel] over every tile the mask reaches. */
    private fun rampLayer(mask: SelectionMask): Map<Long, ByteArray> {
        val out = LinkedHashMap<Long, ByteArray>()
        for (key in mask.tileKeys) {
            val t = ByteArray(Tiles.SIZE * Tiles.SIZE * 4)
            val ox = Tiles.tx(key) * Tiles.SIZE
            val oy = Tiles.ty(key) * Tiles.SIZE
            for (row in 0 until Tiles.SIZE) {
                for (col in 0 until Tiles.SIZE) {
                    val p = rampPixel(ox + col, oy + row)
                    val at = (row * Tiles.SIZE + col) * 4
                    t[at] = p[0].toByte(); t[at + 1] = p[1].toByte()
                    t[at + 2] = p[2].toByte(); t[at + 3] = p[3].toByte()
                }
            }
            out[key] = t
        }
        return out
    }

    /**
     * A change set turned back into a layer, the way `GlPaintEngine.replaceTiles` applies one: a
     * `null` DELETED the tile, so a change set read back as a layer drops those keys rather than
     * inventing an all-zero tile for them. Feeding a change set straight back into [MaskPaint.apply]
     * is a type error rather than a silent wrong answer, which is the right way round.
     */
    private fun Map<Long, ByteArray?>.asLayer(): Map<Long, ByteArray> {
        val out = LinkedHashMap<Long, ByteArray>()
        for ((k, v) in this) if (v != null) out[k] = v
        return out
    }

    /** Total alpha over every tile of a change set — a whole picture reduced to one number. */
    private fun totalAlpha(changed: Map<Long, ByteArray?>): Long {
        var sum = 0L
        for (bytes in changed.values) {
            val t = assertNotNull(bytes, "a fill never empties a tile; a null here is a bug")
            for (i in t.indices step 4) sum += (t[i + 3].toInt() and 0xFF).toLong()
        }
        return sum
    }

    /** The mask's own coverage total over a box, computed through `coverage(x, y)`. */
    private fun coverageSum(mask: SelectionMask, r: RectPx): Long {
        var sum = 0L
        for (y in r.y until r.y + r.h) {
            for (x in r.x until r.x + r.w) sum += mask.coverage(x, y)
        }
        return sum
    }
