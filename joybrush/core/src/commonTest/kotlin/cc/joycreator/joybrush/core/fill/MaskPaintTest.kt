    /**
     * NaN AND OUT-OF-RANGE OPACITY, which is where a slider and a NaN both end up.
     *
     * A NaN is 1, not 0 and not a silent no-op. `Double.coerceIn` returns NaN for NaN (every
     * comparison with NaN is false), and a NaN reaching `a` would make every downstream comparison
     * false and the fill would return an EMPTY change set — a fill that looks exactly like a tap
     * that missed. Out of range is CLAMPED, because it comes off a slider.
     */
    @Test
    fun opacityIsClampedAndNaNBecomesOne() {
        val mask = SelectionMask.rect(RectPx(0, 0, 4, 4))
        val empty = mapOf(Tiles.key(0, 0) to solidTile(0, 0, 0, 0))
        val one = MaskPaint.apply(empty, mask, 0xFFFFFFFF.toInt(), 1f, MaskPaintMode.FILL)
        assertContentEquals(
            one[Tiles.key(0, 0)],
            MaskPaint.apply(empty, mask, 0xFFFFFFFF.toInt(), Float.NaN, MaskPaintMode.FILL)[Tiles.key(0, 0)],
            "NaN must behave as 1",
        )
        assertContentEquals(
            one[Tiles.key(0, 0)],
            MaskPaint.apply(empty, mask, 0xFFFFFFFF.toInt(), 4f, MaskPaintMode.FILL)[Tiles.key(0, 0)],
            "4 is clamped to 1",
        )
        assertTrue(
            MaskPaint.apply(empty, mask, 0xFFFFFFFF.toInt(), -2f, MaskPaintMode.FILL).isEmpty(),
            "-2 is clamped to 0, which is a no-op in every mode",
        )
    }

