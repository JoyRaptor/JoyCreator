"""TextLab icons: lock the final set and write it as Android vector drawables.

    python -I to_android.py <v2.json> <final.json> <res/drawable dir>

Final set (owner, 2026-11-12 late): every v2 icon kept; Depth = the block, now tapering as it goes back;
Sides = the bevelled tile (v1's Depth drawing); the swap entries and the Export drawing are dropped (TextLab
uses Studio's ic_export_studio). Drawables are white; the app tints them (zinc off, ground-coloured on cyan).
"""
import json
import re
import sys

DEPTH = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
         'stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round"><path d="M4.82 8.39H15.82V19.39H4.82Z"/>'
         '<path d="M4.82 8.39L12.8 4.61H19.18L15.82 8.39M19.18 4.61V10.99L15.82 19.39"/></svg>')


def final_set(v2):
    by = {(i['group'], i['word']): i for i in v2}
    out = []
    for i in v2:
        w = i['word']
        if w in ('Depth (swap)', 'Sides (swap)', 'Export'):
            continue
        i = dict(i)
        if w == 'Depth':
            i['svg'] = DEPTH
            i['note'] = 'A block whose faces taper as it goes back: depth and perspective.'
        if w == 'Sides':
            i['svg'] = by[('Properties', 'Sides (swap)')]['svg']
            i['note'] = 'A bevelled tile seen face on: the walls round the face.'
        i.pop('decision', None)
        out.append(i)
    return out


def slug(i):
    s = re.sub(r'[^a-z0-9]+', '_', i['word'].lower()).strip('_')
    return ('ic_tl_' + s) if i['group'] == 'Look row' else ('ic_tl_tab_' + s)


def attrs(s):
    return dict(re.findall(r'([\w-]+)="([^"]*)"', s))


def num(v):
    return float(v)


def fmt(v):
    return ('%.3f' % v).rstrip('0').rstrip('.')


def rect_d(a):
    x, y, w, h = (num(a.get(k, 0)) for k in ('x', 'y', 'width', 'height'))
    rx = num(a.get('rx', a.get('ry', 0)))
    ry = num(a.get('ry', a.get('rx', 0)))
    if rx <= 0:
        return 'M%s %sH%sV%sH%sZ' % (fmt(x), fmt(y), fmt(x + w), fmt(y + h), fmt(x))
    return ('M{a} {y}H{b}A{rx} {ry} 0 0 1 {r} {c}V{d}A{rx} {ry} 0 0 1 {b} {bot}H{a}A{rx} {ry} 0 0 1 {x} {d}V{c}'
            'A{rx} {ry} 0 0 1 {a} {y}Z').format(a=fmt(x + rx), b=fmt(x + w - rx), c=fmt(y + ry), d=fmt(y + h - ry),
                                                 x=fmt(x), y=fmt(y), r=fmt(x + w), bot=fmt(y + h), rx=fmt(rx), ry=fmt(ry))


def ellipse_d(cx, cy, rx, ry):
    return 'M{l} {cy}A{rx} {ry} 0 1 0 {r} {cy}A{rx} {ry} 0 1 0 {l} {cy}Z'.format(
        l=fmt(cx - rx), r=fmt(cx + rx), cy=fmt(cy), rx=fmt(rx), ry=fmt(ry))


def vector(svg):
    top = attrs(re.match(r'<svg([^>]*)>', svg).group(1))
    parts = []
    for tag, rest in re.findall(r'<(path|rect|circle|ellipse)([^>]*)/?>', svg):
        a = attrs(rest)
        if tag == 'path':
            d = a['d']
        elif tag == 'rect':
            d = rect_d(a)
        elif tag == 'circle':
            d = ellipse_d(num(a['cx']), num(a['cy']), num(a['r']), num(a['r']))
        else:
            d = ellipse_d(num(a['cx']), num(a['cy']), num(a['rx']), num(a['ry']))
        fill = a.get('fill', top.get('fill', 'none'))
        stroke = a.get('stroke', top.get('stroke', 'none'))
        p = ['<path android:pathData="%s"' % d]
        if fill != 'none':
            p.append(' android:fillColor="#FFFFFFFF"')
        if stroke != 'none':
            p.append(' android:strokeColor="#FFFFFFFF" android:strokeWidth="%s" android:strokeLineCap="%s"'
                     ' android:strokeLineJoin="%s"' % (a.get('stroke-width', top.get('stroke-width', '1.6')),
                                                      a.get('stroke-linecap', top.get('stroke-linecap', 'round')),
                                                      a.get('stroke-linejoin', top.get('stroke-linejoin', 'round'))))
        p.append('/>')
        line = ''.join(p)
        t = a.get('transform')
        if t:
            m = re.fullmatch(r'rotate\(\s*([-\d.]+)\s+([-\d.]+)\s+([-\d.]+)\s*\)', t.strip())
            if not m:
                raise ValueError('transform not handled: ' + t)
            line = ('<group android:rotation="%s" android:pivotX="%s" android:pivotY="%s">%s</group>'
                    % (m.group(1), m.group(2), m.group(3), line))
        parts.append('    ' + line)
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- TextLab icon, generated by tasks/design/textlab-icons/to_android.py; edit the JSON, not this. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n'
            + '\n'.join(parts) + '\n</vector>\n')


if __name__ == '__main__':
    v2 = json.load(open(sys.argv[1], encoding='utf-8'))
    fin = final_set(v2)
    json.dump(fin, open(sys.argv[2], 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    names = set()
    for i in fin:
        n = slug(i)
        assert n not in names, n
        names.add(n)
        open('%s/%s.xml' % (sys.argv[3], n), 'w', encoding='utf-8', newline='\n').write(vector(i['svg']))
    print(len(fin), 'icons:', ' '.join(sorted(names)))
