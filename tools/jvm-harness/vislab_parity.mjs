// Writes the reference numbers for VisFeatureParityTest: the web pilot's FeatureExtractor
// (tools/vislab-web/vislab-audio.js, loaded as-is) fed a synthetic beat. The Java port must
// reproduce these frame by frame. Both sides build the identical signal and the identical
// Blackman/FFT/dB spectrum (WebAudio's AnalyserNode recipe), so any drift is the extractor.
//
//   node tools/jvm-harness/vislab_parity.mjs   ->  tools/jvm-harness/fixtures/vislab_features.json
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = fs.readFileSync(path.resolve(here, '../vislab-web/vislab-audio.js'), 'utf8');
const ctx = { window: {}, globalThis: {}, Math, Float32Array, Array, Object, Number, Error, console };
ctx.globalThis = ctx;
vm.createContext(ctx);
vm.runInContext(src.replace('typeof window !== \'undefined\' ? window : globalThis', 'globalThis'), ctx);
const { FeatureExtractor } = ctx.VisAudio;

const SR = 48000, N = 2048, FRAMES = 600, HOP = SR / 60;   // 10 s at 60 Hz

// ---- the signal (mirrored exactly in VisFeatureParityTest.signal) ----
function signal(total) {
  const out = new Float32Array(total);
  let seed = 12345;
  const beat = SR * 60 / 124;                 // 124 bpm
  for (let i = 0; i < total; i++) {
    seed = (Math.imul(seed, 1103515245) + 12345) >>> 0;
    const noise = ((seed >>> 8) / 16777216) * 2 - 1;
    const tb = i % beat;
    const kt = tb / SR;
    const kick = tb < SR * 0.35 ? Math.sin(2 * Math.PI * (45 + 115 * Math.exp(-kt * 30)) * kt) * Math.exp(-kt * 9) : 0;
    const half = (i + beat / 2) % beat;
    const hat = half < SR * 0.04 ? noise * 0.25 * Math.exp(-(half / SR) * 90) : 0;
    const pad = 0.12 * Math.sin(2 * Math.PI * 220 * i / SR) + 0.08 * Math.sin(2 * Math.PI * 330 * i / SR + 1.3);
    out[i] = Math.fround(kick * 0.8 + hat + pad * (i > SR * 4 ? 1 : 0.3));
  }
  return out;
}

// ---- WebAudio-style analyser: Blackman window, FFT, |X|/N, 20 log10 ----
const win = new Float32Array(N);
for (let i = 0; i < N; i++) { const x = 2 * Math.PI * i / N; win[i] = Math.fround(0.42 - 0.5 * Math.cos(x) + 0.08 * Math.cos(2 * x)); }
function fft(re, im) {   // same radix-2 as com.fadcam.ui.faditor.waveform.Fft (float maths)
  const n = re.length;
  for (let i = 1, j = 0; i < n; i++) {
    let bit = n >> 1;
    for (; j & bit; bit >>= 1) j ^= bit;
    j ^= bit;
    if (i < j) { let t = re[i]; re[i] = re[j]; re[j] = t; t = im[i]; im[i] = im[j]; im[j] = t; }
  }
  for (let len = 2; len <= n; len <<= 1) {
    const ang = -2 * Math.PI / len;
    const wr0 = Math.fround(Math.cos(ang)), wi0 = Math.fround(Math.sin(ang));
    for (let i = 0; i < n; i += len) {
      let wr = 1, wi = 0;
      const half = len >> 1;
      for (let k = 0; k < half; k++) {
        const a = i + k, b = i + k + half;
        const vr = Math.fround(Math.fround(re[b] * wr) - Math.fround(im[b] * wi));
        const vi = Math.fround(Math.fround(re[b] * wi) + Math.fround(im[b] * wr));
        re[b] = Math.fround(re[a] - vr); im[b] = Math.fround(im[a] - vi);
        re[a] = Math.fround(re[a] + vr); im[a] = Math.fround(im[a] + vi);
        const nwr = Math.fround(Math.fround(wr * wr0) - Math.fround(wi * wi0));
        wi = Math.fround(Math.fround(wr * wi0) + Math.fround(wi * wr0));
        wr = nwr;
      }
    }
  }
}
function spectrum(mono) {
  const re = new Float32Array(N), im = new Float32Array(N), db = new Float32Array(N / 2);
  for (let i = 0; i < N; i++) re[i] = Math.fround(mono[i] * win[i]);
  fft(re, im);
  const inv = Math.fround(1 / N);
  for (let k = 0; k < N / 2; k++) db[k] = Math.fround(20 * Math.log10(Math.sqrt(re[k] * re[k] + im[k] * im[k]) * inv));
  return db;
}

const sig = signal(N + FRAMES * HOP);
const fx = new FeatureExtractor(SR, N);
const frames = [];
let kicks = 0;
for (let f = 0; f < FRAMES; f++) {
  const end = N + f * HOP;
  const block = sig.subarray(end - N, end);
  const fr = fx.update(spectrum(block), block, null, 1 / 60);
  if (fr.punch > 0) kicks++;
  if (f % 10 === 0 || fr.punch > 0) {
    frames.push({ f, bass: fr.bass, mid: fr.mid, high: fr.high, level: fr.level, voice: fr.voice, bright: fr.bright,
      kick: fr.kick, hat: fr.hat, beat: fr.beat, beatPhase: fr.beatPhase, punch: fr.punch, bpm: fr.bpm,
      spec40: fr.spec[40], spec90: fr.spec[90], raw20: fr.raw[20], wave100: fr.waveL[100] });
  }
}
const out = { note: 'generated by vislab_parity.mjs from tools/vislab-web/vislab-audio.js', sampleRate: SR, fft: N, frames: FRAMES, kicks, samples: frames };
fs.mkdirSync(path.join(here, 'fixtures'), { recursive: true });
fs.writeFileSync(path.join(here, 'fixtures', 'vislab_features.json'), JSON.stringify(out, null, 1));
console.log('frames', FRAMES, 'kicks', kicks, 'samples', frames.length, 'final bpm', frames[frames.length - 1].bpm.toFixed(1));
